#!/usr/bin/env python3
"""Generates lib/features/exercises/data/exercise_catalog.dart from the text
extracted from the exercise guide docx (Part A master list + Part B filming
details). Usage: gen_exercise_catalog.py guide.txt > exercise_catalog.dart"""
import html, re, sys

L = [html.unescape(x) for x in open(sys.argv[1], encoding='utf8').read().split('\n')]
partb = next(i for i, l in enumerate(L) if l.startswith('Part B —'))

LEVELS = {'Beginner': 'beginner', 'Beginner–Intermediate': 'begInt', 'Intermediate': 'intermediate',
          'Intermediate–Advanced': 'intAdv', 'Advanced': 'advanced'}
SECTIONS = {
 '1A': ('foundation-upper', 'Foundation — Upper Body'), '1B': ('foundation-core', 'Foundation — Core'),
 '1C': ('foundation-legs', 'Foundation — Legs & Glutes'), '1D': ('foundation-conditioning', 'Foundation — Conditioning'),
 '2.1': ('skill-pull-up', 'Skill — Pull-Up'), '2.2': ('skill-push-up', 'Skill — Push-Up'),
 '2.3': ('skill-pistol-squat', 'Skill — Pistol Squat'), '2.4': ('skill-l-sit', 'Skill — L-Sit'),
 '2.5': ('skill-handstand', 'Skill — Handstand'), '2.6': ('skill-dips', 'Skill — Dips'),
 '2.7': ('skill-chin-up', 'Skill — Chin-Up'), '2.8': ('skill-toes-to-bar', 'Skill — Toes-to-Bar'),
 '3.': ('warmup-mobility', 'Warm-Up, Mobility & Cool-Down'), '4.': ('extras', 'Extra Variations & Equipment Alternatives'),
}
rows = {}
i = 33
while i < partb:
    if L[i] == '#' and L[i + 1] == 'Exercise':
        head = L[i - 2]
        key = next(k for k in SECTIONS if head.startswith(k))
        sid = SECTIONS[key][0]
        j = i + 5
        while j + 4 < partb and L[j].isdigit():
            n = int(L[j]); name, lvl, eq, f = L[j+1], L[j+2], L[j+3], L[j+4]
            equipment, _, purpose = eq.partition(' — ')
            same = re.match(r'Same video as #(\d+)', f)
            rows[n] = dict(n=n, name=name, level=LEVELS[lvl], equipment=equipment, purpose=purpose,
                           section=sid, file=None if same else f, same=int(same.group(1)) if same else None)
            j += 5
        i = j
    else:
        i += 1
assert sorted(rows) == list(range(1, 116)), len(rows)

details = {}
k = partb
while k < len(L):
    m = re.match(r'#(\d+)\s+(.*)', L[k])
    if not m:
        k += 1; continue
    n = int(m.group(1)); d = {'steps': []}; k += 1; mode = None
    while k < len(L) and not re.match(r'#\d+\s', L[k]):
        l = L[k]
        if l.startswith('Starting position:'): d['start'] = l.split(':', 1)[1].strip(); mode = None
        elif l.startswith('How to perform:'): mode = 'steps'
        elif l.startswith('Breathing:'): d['breathing'] = l.split(':', 1)[1].strip(); mode = None
        elif l.startswith('Key cues to show:'): d['cues'] = l.split(':', 1)[1].strip(); mode = None
        elif l.startswith('Common mistakes to avoid:'): d['mistakes'] = l.split(':', 1)[1].strip(); mode = None
        elif l.startswith('Safety:'): d['safety'] = l.split(':', 1)[1].strip(); mode = None
        elif l.startswith('Easier / harder:'):
            t = l.split(':', 1)[1]
            e = re.search(r'Easier:\s*(.*?)(?:\s+Harder:|$)', t); h = re.search(r'Harder:\s*(.*)$', t)
            d['easier'] = e.group(1).strip() if e else None; d['harder'] = h.group(1).strip() if h else None; mode = None
        elif l.startswith('Camera:'): d['camera'] = l.split(':', 1)[1].strip(); mode = None
        elif l.startswith('What to film:'): d['film'] = l.split(':', 1)[1].strip(); mode = None
        elif l.startswith(('File:', 'Level:', 'Also used for:')): mode = None
        elif mode == 'steps': d['steps'].append(l.strip())
        k += 1
    details[n] = d

def q(s):
    if s is None: return 'null'
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$') + "'"

out = ["// GENERATED by tool/gen_exercise_catalog.py from the Calesthetics exercise guide.",
       "// Do not edit by hand — re-run the generator.", "",
       "import '../domain/exercise.dart';", "",
       "const exerciseSections = ["]
for key, (sid, title) in SECTIONS.items():
    out.append(f"  ExerciseSection(id: {q(sid)}, title: {q(title)}),")
out += ["];", "", "const exerciseCatalog = ["]
for n in range(1, 116):
    r = rows[n]; canon = r['same'] or n; d = details.get(canon, {})
    steps = '[' + ', '.join(q(s) for s in d.get('steps', [])) + ']'
    out.append(f"""  Exercise(
    number: {n},
    name: {q(r['name'])},
    level: ExerciseLevel.{r['level']},
    sectionId: {q(r['section'])},
    equipment: {q(r['equipment'])},
    purpose: {q(r['purpose'])},
    videoNumber: {canon},
    videoFile: {q(rows[canon]['file'])},
    startingPosition: {q(d.get('start'))},
    steps: {steps},
    breathing: {q(d.get('breathing'))},
    cues: {q(d.get('cues'))},
    mistakes: {q(d.get('mistakes'))},
    safety: {q(d.get('safety'))},
    easier: {q(d.get('easier'))},
    harder: {q(d.get('harder'))},
  ),""")
out.append("];")
print('\n'.join(out))
