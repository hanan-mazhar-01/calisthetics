#!/usr/bin/env python3
"""Compresses the exercise videos and uploads them to Bunny Stream.

  python3 tool/bunny_upload_videos.py "<videos folder>" [--only 1,2,3] [--dry-run]

* Main videos (~30 s) keep their sound; rest clips (~10 s) are made silent.
* Every video is re-encoded to 720x1280 H.264 with +faststart before upload
  (Bunny then makes the 240p-720p renditions for adaptive playback).
* State (file hash -> Bunny video id) lives in tool/stream_videos.json, so a
  re-run only uploads what changed. The app reads the generated
  lib/features/media/data/bunny_videos.g.dart (ids only, nothing secret).

Credentials: BUNNY_STREAM_LIBRARY / BUNNY_STREAM_KEY / BUNNY_STREAM_CDN in
~/.config/calesthetics/bunny.env. The key is never shipped in the app.
"""
import argparse, hashlib, json, os, subprocess, sys, tempfile, urllib.request
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import bunny_upload_images as up  # noqa: E402  (load_env)
from videos_match import FFMPEG, match  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
STATE = ROOT / "tool/stream_videos.json"
OUT_DART = ROOT / "lib/features/media/data/bunny_videos.g.dart"
API = "https://video.bunnycdn.com/library"


def encode(src: Path, dst: Path, sound: bool):
    cmd = [FFMPEG, "-loglevel", "error", "-y", "-i", str(src),
           "-vf", "scale=720:1280:force_original_aspect_ratio=decrease,pad=720:1280:(ow-iw)/2:(oh-ih)/2,fps=30",
           "-c:v", "libx264", "-preset", "slow", "-crf", "23", "-pix_fmt", "yuv420p",
           "-movflags", "+faststart"]
    cmd += ["-c:a", "aac", "-b:a", "96k", "-ac", "2"] if sound else ["-an"]
    subprocess.run(cmd + [str(dst)], check=True)


def api(method, path, body=None, data=None):
    headers = {"AccessKey": os.environ["BUNNY_STREAM_KEY"], "accept": "application/json"}
    if body is not None:
        data = json.dumps(body).encode(); headers["content-type"] = "application/json"
    elif data is not None:
        headers["content-type"] = "application/octet-stream"
    req = urllib.request.Request(f"{API}/{os.environ['BUNNY_STREAM_LIBRARY']}{path}",
                                 data=data, method=method, headers=headers)
    with urllib.request.urlopen(req, timeout=600) as r:
        raw = r.read()
        return json.loads(raw) if raw else {}


def upload(title: str, file: Path) -> str:
    guid = api("POST", "/videos", {"title": title})["guid"]
    api("PUT", f"/videos/{guid}", data=file.read_bytes())
    return guid


def write_dart(state):
    lines = []
    for stem in sorted(state):
        e = state[stem]
        main = e.get("main", {}).get("guid")
        clip = e.get("clip", {}).get("guid")
        lines.append(f"  '{stem}': ({_q(main)}, {_q(clip)}),")
    OUT_DART.write_text(
        "// GENERATED by tool/bunny_upload_videos.py - do not edit by hand.\n"
        "// Video file stem -> (main video id, rest clip id) on Bunny Stream.\n"
        "const bunnyVideos = <String, (String?, String?)>{\n" + "\n".join(lines) + "\n};\n")


def _q(v):
    return "null" if v is None else f"'{v}'"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("source")
    ap.add_argument("--only", help="comma separated catalog numbers")
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()
    up.load_env(required=("BUNNY_STREAM_LIBRARY", "BUNNY_STREAM_KEY"))
    for k in ("BUNNY_STREAM_LIBRARY", "BUNNY_STREAM_KEY"):
        if not os.environ.get(k):
            sys.exit(f"Missing {k}")
    matched, _ = match(a.source)
    only = {int(x) for x in a.only.split(",")} if a.only else None
    state = json.loads(STATE.read_text()) if STATE.exists() else {}
    tmp = Path(tempfile.mkdtemp(prefix="calvid_"))
    total_in = total_out = 0
    for v, r in matched.items():
        if only and v not in only:
            continue
        stem = r["file"].removesuffix(".mp4")
        # An exercise without its 30 s video shows its clip in both places.
        kinds = [("main", r["main"] or r["clip"], bool(r["main"])), ("clip", r["clip"], False)]
        for kind, src, sound in kinds:
            if not src:
                continue
            src = Path(src)
            out = tmp / f"{stem}_{kind}.mp4"
            encode(src, out, sound)
            digest = hashlib.sha1(out.read_bytes()).hexdigest()[:12]
            total_in += src.stat().st_size; total_out += out.stat().st_size
            prev = state.get(stem, {}).get(kind)
            if prev and prev.get("sha") == digest:
                print(f"= #{v} {kind:4s} unchanged")
                continue
            print(f"↑ #{v} {kind:4s} {src.stat().st_size/1e6:5.1f} MB -> {out.stat().st_size/1e6:4.1f} MB  {src.name}")
            if a.dry_run:
                continue
            guid = upload(f"{stem}{'' if kind == 'main' else '__clip'}", out)
            if prev and prev.get("guid"):
                try:
                    api("DELETE", f"/videos/{prev['guid']}")
                except Exception as e:  # old copy stays; harmless
                    print("  (could not delete old copy:", e, ")")
            state.setdefault(stem, {})[kind] = {"guid": guid, "sha": digest, "source": str(src.relative_to(a.source))}
            STATE.write_text(json.dumps(state, indent=1, sort_keys=True))
            write_dart(state)
    print(f"\n{total_in/1e6:.0f} MB -> {total_out/1e6:.0f} MB")
    if not a.dry_run:
        write_dart(state)


if __name__ == "__main__":
    main()
